"""PDF report generation (reportlab)."""
from __future__ import annotations

from datetime import datetime
from pathlib import Path


def build_report_pdf(job_id: str, job_row, result: dict, out_path: Path) -> Path:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer,
                                    Table, TableStyle)
    from reportlab.lib.styles import getSampleStyleSheet

    styles = getSampleStyleSheet()
    doc = SimpleDocTemplate(
        str(out_path), pagesize=A4,
        leftMargin=18 * mm, rightMargin=18 * mm,
        topMargin=16 * mm, bottomMargin=16 * mm,
        title=f"Traffic Violation Report - {job_id}",
    )
    story = []
    story.append(Paragraph("Traffic Violation Detection - Report",
                           styles["Title"]))
    story.append(Spacer(1, 4 * mm))
    meta = [
        ["Job ID", job_id],
        ["Source video", job_row["filename"]],
        ["Generated", datetime.now().strftime("%d %b %Y, %H:%M")],
        ["Duration (s)", str(result.get("duration_s", ""))],
        ["Vehicles tracked", str(result.get("total_vehicles", ""))],
        ["Vehicles breaking rules", str(result.get("total_violating_vehicles", ""))],
        ["Compliant vehicles", str(result.get("compliant_vehicles", ""))],
        ["Vehicles by class", ", ".join(
            f"{k}: {v}" for k, v in (result.get("vehicle_counts") or {}).items()) or "-"],
        ["Violation events", str(result.get("total_violations", ""))],
        ["Violations by type", ", ".join(
            f"{k}: {v}" for k, v in (result.get("violation_counts") or {}).items()) or "-"],
    ]
    story.append(Table(meta, colWidths=[45 * mm, 115 * mm], style=TableStyle([
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#f5f5f5")),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
    ])))
    story.append(Spacer(1, 8 * mm))

    violations = result.get("violations", [])
    story.append(Paragraph(f"Violation log ({len(violations)})", styles["Heading2"]))
    headers = ["#", "Type", "Track", "Vehicle", "Time (s)", "Speed (km/h)", "Detail"]
    rows = [[str(v["id"]), v["label"], str(v["track_id"]), v["vehicle"],
             str(v["timestamp_s"]), str(v["speed_kmh"]), v["detail"]] for v in violations]
    table = Table([headers] + rows,
                  colWidths=[10 * mm, 26 * mm, 14 * mm, 24 * mm, 20 * mm, 26 * mm, 40 * mm],
                  repeatRows=1)
    table.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#222222")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#fafafa")]),
    ]))
    story.append(table)
    story.append(Spacer(1, 8 * mm))
    story.append(Paragraph(
        "Generated by Crouton Alpha Traffic Violation Detection. "
        "Speeds are estimated from centroid motion with user calibration; "
        "helmet detection uses a colour heuristic and is indicative only.",
        styles["BodyText"]))
    doc.build(story)
    return out_path
